/**
 * Виды, которые проставляет автор поста, — в отличие от всех остальных, которые
 * выводятся из блюда или проставляются модератором.
 *
 * Граница проходит по одному признаку: знает ли это только тот, кто ел. Была ли
 * шаурма веганской и насколько она острая — знает он, и вывести это из блюда
 * нельзя. Стритфуд это или суп — свойство самого блюда, одинаковое для всех его
 * позиций, и спрашивать об этом автора значит просить его гадать.
 *
 * Тот же список лежит в `posts/models.py::AUTHOR_TAXON_SLUGS` и там же
 * проверяется на входе: пришлёт клиент лишнее — вернётся ошибка. Меняя здесь,
 * менять и там.
 */
export const AUTHOR_TAXON_SLUGS = [
  "vegetarian",
  "vegan",
  "healthy",
  "lenten",
  "spicy",
  "gluten-free",
  "lactose-free",
  "halal",
  "kids",
] as const;

export function isAuthorTaxon(slug: string): boolean {
  return (AUTHOR_TAXON_SLUGS as readonly string[]).includes(slug);
}
